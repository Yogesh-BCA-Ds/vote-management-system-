CREATE TABLE IF NOT EXISTS newuser (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('voter', 'admin', 'candidate')),
    date_joined TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_login TIMESTAMP,
    is_verified BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS election (
    election_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    des TEXT NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    election_type TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('upcoming', 'ongoing', 'completed')),
    elg TEXT NOT NULL,
    result_date TIMESTAMP,
    CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS voters (
    profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES newuser(user_id) ON DELETE CASCADE,
    phone TEXT NOT NULL,
    adress TEXT NOT NULL,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    country TEXT NOT NULL,
    voting_history TEXT,
    activity_log TEXT,
    is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS candidate (
    candidate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    election_id BIGINT NOT NULL REFERENCES election(election_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    party TEXT,
    manifesto TEXT,
    vote_count INTEGER DEFAULT 0 CHECK (vote_count >= 0)
);

CREATE TABLE IF NOT EXISTS vote (
    vote_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES newuser(user_id),
    election_id BIGINT NOT NULL REFERENCES election(election_id),
    candidate_id BIGINT NOT NULL REFERENCES candidate(candidate_id),
    "timestamp" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_valid BOOLEAN DEFAULT TRUE,
    UNIQUE (user_id, election_id)
);
